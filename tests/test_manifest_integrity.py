"""Kiểm tra danh mục SHA-256 không bỏ sót nguồn và metadata."""
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory
from unittest.mock import patch
import verify_independent_processes as verifier
from verify_independent_processes import collect_version_manifest


class TestManifestIntegrity(unittest.TestCase):
    def test_manifest_covers_algorithms_and_scenario_metadata(self):
        entries, fingerprint = collect_version_manifest()
        files = {entry["file"] for entry in entries}
        for name in ["graph.py", "bfs.py", "edmonds_karp.py",
                     "ford_fulkerson.py", "min_cut.py", "validator.py",
                     "scenario.py", "main.py", "cpp_edmonds_karp.cpp",
                     "data/Nodes.csv", "data/Scenarios.csv",
                     "tests/test_edge_cases.py", "VIET_TAY.md"]:
            self.assertIn(name, files)
        for sid in ["SC01", "SC02", "SC03", "SC04", "SC05"]:
            for table in ["Edges.csv", "Lane_Groups.csv", "Movements.csv"]:
                self.assertIn(f"data/scenarios/{sid}/{table}", files)
        self.assertTrue(all(len(e["sha256"]) == 64 for e in entries))
        self.assertEqual(len(fingerprint), 64)
        self.assertFalse(any(p.startswith("outputs/") for p in files))
        self.assertFalse(any("__pycache__" in p for p in files))

    def test_manifest_ignores_generated_pytest_cache(self):
        # Cache is generated by pytest, not source code: must not break SHA-256.
        with TemporaryDirectory() as folder:
            root = Path(folder)
            (root / "graph.py").write_text("# algorithm\n", encoding="utf-8")
            cache = root / ".pytest_cache"
            cache.mkdir()
            (cache / "README.md").write_text("generated cache", encoding="utf-8")
            pycache = root / "__pycache__"
            pycache.mkdir()
            (pycache / "generated.py").write_text("# cache", encoding="utf-8")
            with patch.object(verifier, "ROOT", root):
                entries, fingerprint1 = verifier.collect_version_manifest()
                (cache / "README.md").write_text("new generated cache", encoding="utf-8")
                other, fingerprint2 = verifier.collect_version_manifest()
            self.assertEqual([entry["file"] for entry in entries], ["graph.py"])
            self.assertEqual(fingerprint1, fingerprint2)


if __name__ == "__main__":
    unittest.main()
